"""Generated workflow rendering tests."""

import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from reviewer import defaults, files  # noqa: E402


class WorkflowTest(unittest.TestCase):
    def setUp(self):
        self.config = {
            "provider": "gemini",
            "model": "gemini-2.5-flash",
            "base_url": "",
            "runner": "ubuntu-latest",
            "extra_instructions": 'Say "hi" and use ${{ github.token }} literally',
        }

    def test_required_lines(self):
        text = files.render_workflow(self.config)
        self.assertIn("Generated by reviewer", text)
        self.assertIn("name: review", text)
        self.assertIn("pull_request:", text)
        self.assertIn("sparse-checkout: |", text)
        self.assertIn("            .github/reviewer", text)
        self.assertIn("run: python3 .github/reviewer/review.py", text)
        self.assertIn("PR_NUMBER: ${{ github.event.pull_request.number }}", text)
        self.assertEqual(text.count("${{ secrets." + defaults.SECRET_NAME + " }}"), 1)

    def test_json_quoted_env_scalars(self):
        text = files.render_workflow(self.config)
        self.assertIn('MODEL: "gemini-2.5-flash"', text)
        self.assertIn('RUNNER: "ubuntu-latest"', text.replace("runs-on:", "RUNNER:"))
        self.assertIn('BASE_URL: ""', text)
        self.assertIn('EXTRA_INSTRUCTIONS: "Say \\"hi\\" and use $ { { github.token }} literally"', text)

    def test_actions_expression_is_neutralized(self):
        self.assertEqual(files.neutralize_actions_expression("${{ x }}"), "$ { { x }}")

    def test_build_contents_has_three_paths(self):
        contents = files.build_contents(self.config)
        self.assertEqual(sorted(contents), sorted(defaults.GENERATED_PATHS))
        for path, text in contents.items():
            self.assertIn("SPDX-License-Identifier: Apache-2.0", text, path)
            self.assertIn("Copyright 2026 Aariso0", text, path)

    def test_plan_markers(self):
        import tempfile
        from pathlib import Path
        with tempfile.TemporaryDirectory() as tmp:
            contents = {".github/workflows/pr-review.yml": "new unmarked\n"}
            target = Path(tmp) / ".github/workflows/pr-review.yml"
            target.parent.mkdir(parents=True)
            target.write_text("unmarked\n", encoding="utf-8")
            rows = files.plan(tmp, contents)
            self.assertEqual(rows[0]["status"], "overwrite")
            self.assertTrue(rows[0]["unmarked"])
            written = files.write_plan(tmp, rows)
            self.assertEqual(written, [".github/workflows/pr-review.yml"])
            rows = files.plan(tmp, contents)
            self.assertEqual(rows[0]["status"], "unchanged")
            self.assertFalse(rows[0]["unmarked"])


if __name__ == "__main__":
    unittest.main()
