"""Render, compare and write the three generated repository files."""

import json
from pathlib import Path

from .defaults import MARKER

_DATA_DIR = Path(__file__).resolve().parent / "data"


def bundled_text(filename):
    """Read a bundled data file included in wheels and sdists."""
    with open(str(_DATA_DIR / filename), "r", encoding="utf-8") as handle:
        return handle.read()


def neutralize_actions_expression(text):
    """Prevent user rules from being evaluated as a GitHub Actions expression."""
    return (text or "").replace("${{", "$ { {")


def json_scalar(value):
    """Return a JSON-quoted string, which is also a valid YAML scalar."""
    return json.dumps(value or "", ensure_ascii=False)


def render_workflow(config):
    """Render .github/workflows/pr-review.yml."""
    provider = config.get("provider", "")
    model = config.get("model", "")
    base_url = config.get("base_url", "")
    runner = config.get("runner", "ubuntu-latest")
    extra = neutralize_actions_expression(config.get("extra_instructions", ""))
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# Copyright 2026 Aariso0",
        "# " + MARKER + ". Re-run `reviewer init` to change settings.",
        "name: review",
        "",
        "on:",
        "  pull_request:",
        "    types: [opened, synchronize, reopened, ready_for_review]",
        "",
        "jobs:",
        "  review:",
        "    name: review",
        "    if: github.event.pull_request.draft == false",
        "    runs-on: " + json_scalar(runner),
        "    permissions:",
        "      contents: read",
        "      pull-requests: write",
        "    steps:",
        "      - uses: actions/checkout@v4",
        "        with:",
        "          sparse-checkout: |",
        "            .github/reviewer",
        "      - name: Run review",
        "        run: python3 .github/reviewer/review.py",
        "        env:",
        "          PROVIDER: " + json_scalar(provider),
        "          MODEL: " + json_scalar(model),
        "          BASE_URL: " + json_scalar(base_url),
        "          EXTRA_INSTRUCTIONS: " + json_scalar(extra),
        "          AI_REVIEW_API_KEY: ${{ secrets.AI_REVIEW_API_KEY }}",
        "          GITHUB_TOKEN: ${{ github.token }}",
        "          PR_NUMBER: ${{ github.event.pull_request.number }}",
        "",
    ]
    return "\n".join(lines)


def build_contents(config):
    """Return a mapping of relative path to rendered content."""
    return {
        ".github/reviewer/review.py": bundled_text("review.py"),
        ".github/reviewer/prompt.md": bundled_text("prompt.md"),
        ".github/workflows/pr-review.yml": render_workflow(config),
    }


def plan(repo_root, contents):
    """Compare rendered content with what is on disk.

    Returns a list of dicts with path, status, content and unmarked.
    """
    rows = []
    for relpath in sorted(contents):
        content = contents[relpath]
        target = Path(repo_root) / relpath
        try:
            existing = target.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            existing = None
        if existing is None:
            status, unmarked = "create", False
        elif existing == content:
            status, unmarked = "unchanged", False
        else:
            status = "overwrite"
            unmarked = MARKER not in existing
        rows.append({
            "path": relpath,
            "status": status,
            "content": content,
            "unmarked": unmarked,
        })
    return rows


def write_plan(repo_root, rows):
    """Write every row whose status is not 'unchanged'. Returns written paths."""
    written = []
    for row in rows:
        if row["status"] == "unchanged":
            continue
        target = Path(repo_root) / row["path"]
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(str(target), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(row["content"])
        written.append(row["path"])
    return written


def format_plan(rows):
    """Return the plain aligned summary list."""
    width = max(len(row["path"]) for row in rows) if rows else 0
    lines = []
    for row in rows:
        note = "  (no marker: not generated by reviewer)" if row["unmarked"] else ""
        lines.append("  {0}  {1}{2}".format(row["path"].ljust(width), row["status"], note))
    return "\n".join(lines)
