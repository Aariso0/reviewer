ANSWER_KEYS = ("provider", "model", "base_url", "runner", "extra_instructions")


def config_dir():
    """Return the per-user configuration directory (created on write only)."""
    return Path.home() / ".config" / "reviewer"


def _read_json(path):
    try:
        with open(str(path), "r", encoding="utf-8") as handle:
            data = json.load(handle)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def load_defaults():
    """Load remembered non-secret answers; unknown keys are ignored."""
    data = _read_json(config_dir() / "defaults.json")
    return {key: data[key] for key in ANSWER_KEYS if isinstance(data.get(key), str)}


def save_defaults(answers):
    """Persist remembered non-secret answers. Failures are non-fatal."""
    path = config_dir() / "defaults.json"
    data = _read_json(path)
    for key in ANSWER_KEYS:
        if key in answers:
            data[key] = answers[key]
    _write_private(path, json.dumps(data, indent=2, sort_keys=True) + "\n")


def load_saved_key():
    """Return a previously saved API key, or an empty string."""
    path = config_dir() / "api_key"
    try:
        with open(str(path), "r", encoding="utf-8") as handle:
            return handle.read().strip()
    except OSError:
        return ""


def save_key(key):
    """Save the API key with mode 600. Failures are returned as a message."""
    path = config_dir() / "api_key"
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        _write_private(path, key + "\n")
        return ""
    except OSError as exc:
        return str(exc)


def _write_private(path, text):
    """Write a file that is never group- or world-readable."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
    except Exception:
        os.close(fd)
        raise
    os.chmod(str(path), 0o600)
